#!/usr/bin/env python3
"""Regenerate this example's translation units.

WHY THIS EXAMPLE IS GENERATED. Every other example here is minimal on
purpose: one source file, so a reader can see the whole thing. This one
exists for the opposite reason -- it is the WIDE build, the subject of
RunQuota's M1 socket-baseline measurement, and its only interesting
property is that it produces MANY INDEPENDENT COMPILE ACTIONS that the
scheduler must admit concurrently. A hand-written wide project would be
the same file pasted N times; the generator says so honestly and keeps
the count and the per-unit cost in one place where they can be changed
and re-justified.

The units are deliberately arithmetic-heavy and header-free so that each
`cc -c` costs tens of milliseconds of real compiler work rather than
being dominated by process startup: an action that costs nothing makes
admission look expensive by comparison, which would flatter exactly the
figure M1 exists to establish.

WHY 64 AND NOT MORE. The engine launches every ready action at once when
RunQuota is bypassed (`--no-runquota`), so the width of this example is
also the number of simultaneously live child processes in that
configuration. At 128 units that exceeded the build daemon's 256-file
descriptor soft limit on macOS and 16 of the 130 actions failed with
"process launch failed: Too many open files" -- the RunQuota arm, whose
concurrency the lease authority bounds, did not. 64 units keeps BOTH
configurations completing, which a paired A/B measurement requires; the
asymmetry itself is recorded in the M1 findings document rather than
being tuned away.
"""

import pathlib

UNITS = 64
FUNCS_PER_UNIT = 5
TERMS = 10

root = pathlib.Path(__file__).parent
src = root / "src"
src.mkdir(exist_ok=True)

for old in src.glob("*.c"):
    old.unlink()

for u in range(UNITS):
    body = [f"/* generated by generate-sources.py; unit {u} of {UNITS} */", ""]
    for f in range(FUNCS_PER_UNIT):
        body.append(f"unsigned long wide_u{u}_f{f}(unsigned long x) {{")
        body.append("    unsigned long a = x, b = x ^ 0x9e3779b9UL, c = 1UL;")
        for t in range(TERMS):
            body.append(f"    a = a * {2 * t + 3}UL + (b >> {(t % 13) + 1});")
            body.append(f"    b = b ^ (a << {(t % 7) + 1}) ^ (c + {t}UL);")
            body.append(f"    c = c + (a & b) - (a | b) + {t * 7 + 1}UL;")
        body.append("    return a ^ b ^ c;")
        body.append("}")
        body.append("")
    body.append(f"unsigned long wide_unit_{u}(unsigned long x) {{")
    body.append("    unsigned long acc = x;")
    for f in range(FUNCS_PER_UNIT):
        body.append(f"    acc ^= wide_u{u}_f{f}(acc + {f}UL);")
    body.append("    return acc;")
    body.append("}")
    (src / f"unit_{u:03d}.c").write_text("\n".join(body) + "\n")

main = ["/* generated by generate-sources.py */", "#include <stdio.h>", ""]
for u in range(UNITS):
    main.append(f"unsigned long wide_unit_{u}(unsigned long x);")
main.append("")
main.append("int main(void) {")
main.append("    unsigned long acc = 1UL;")
for u in range(UNITS):
    main.append(f"    acc ^= wide_unit_{u}(acc);")
main.append('    printf("wide-binary ok %lu\\n", acc & 0xffUL);')
main.append("    return 0;")
main.append("}")
(src / "main.c").write_text("\n".join(main) + "\n")

print(f"generated {UNITS} units + main.c in {src}")
